-- =============================================================
-- 企业培训管理系统 数据库初始化脚本
-- 目标库：enterprise_training    数据库版本：MySQL 5.7.15（兼容 8.0）
-- 字符集：utf8mb4 / utf8mb4_general_ci（5.7 不支持 0900_ai_ci）
-- 执行方式：mysql -uroot -p --default-character-set=utf8mb4 < init.sql
-- =============================================================

/*存在已有数据库则删除重建*/
DROP DATABASE IF EXISTS enterprise_training;
CREATE DATABASE enterprise_training
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_general_ci;
USE enterprise_training;

SET NAMES utf8mb4;

-- -------------------------------------------------------------
-- 1. 部门表（树形，parent_id=0 为根）
-- -------------------------------------------------------------
CREATE TABLE sys_dept (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    name        VARCHAR(64)  NOT NULL COMMENT '部门名称',
    parent_id   BIGINT       NOT NULL DEFAULT 0 COMMENT '上级部门id，0为根',
    sort        INT          NOT NULL DEFAULT 0 COMMENT '排序',
    status      TINYINT      NOT NULL DEFAULT 0 COMMENT '0正常 1停用',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    deleted     TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除 0否 1是',
    PRIMARY KEY (id),
    KEY idx_parent (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='部门表';

-- -------------------------------------------------------------
-- 2. 用户表（一个账号三种角色：ADMIN / TEACHER / STUDENT）
-- -------------------------------------------------------------
CREATE TABLE sys_user (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    username    VARCHAR(50)  NOT NULL COMMENT '登录账号',
    password    VARCHAR(100) NOT NULL COMMENT 'BCrypt 密码',
    real_name   VARCHAR(50)  NOT NULL COMMENT '姓名',
    dept_id     BIGINT       NOT NULL COMMENT '所属部门',
    role        VARCHAR(20)  NOT NULL DEFAULT 'STUDENT' COMMENT 'ADMIN/TEACHER/STUDENT',
    phone       VARCHAR(20)  DEFAULT NULL COMMENT '手机号',
    status      TINYINT      NOT NULL DEFAULT 0 COMMENT '0正常 1禁用',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    deleted     TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_username (username),
    KEY idx_dept (dept_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='用户表';

-- -------------------------------------------------------------
-- 3. 课程表
-- -------------------------------------------------------------
CREATE TABLE course (
    id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    title        VARCHAR(120) NOT NULL COMMENT '课程名称',
    category     VARCHAR(50)  NOT NULL COMMENT '分类：新员工/技术/管理/合规',
    teacher_name VARCHAR(50)  DEFAULT NULL COMMENT '讲师姓名',
    hours        INT          NOT NULL DEFAULT 0 COMMENT '课时（小时）',
    cover_url    VARCHAR(255) DEFAULT NULL COMMENT '封面图',
    intro        TEXT         COMMENT '课程简介',
    status       TINYINT      NOT NULL DEFAULT 0 COMMENT '0下架 1上架',
    create_time  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    deleted      TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    PRIMARY KEY (id),
    KEY idx_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='课程表';

-- -------------------------------------------------------------
-- 4. 课程章节表
-- -------------------------------------------------------------
CREATE TABLE course_chapter (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    course_id   BIGINT       NOT NULL COMMENT '所属课程',
    title       VARCHAR(120) NOT NULL COMMENT '章节标题',
    type        VARCHAR(20)  NOT NULL DEFAULT 'VIDEO' COMMENT 'VIDEO视频 DOC文档',
    duration    INT          NOT NULL DEFAULT 0 COMMENT '时长（分钟）',
    content     TEXT         COMMENT '正文/视频地址',
    sort        INT          NOT NULL DEFAULT 0 COMMENT '章节序号',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    deleted     TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    PRIMARY KEY (id),
    KEY idx_course (course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='课程章节表';

-- -------------------------------------------------------------
-- 5. 培训班表（关联课程，带名额与乐观锁）
-- -------------------------------------------------------------
CREATE TABLE train_class (
    id             BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    name           VARCHAR(120) NOT NULL COMMENT '培训班名称',
    course_id      BIGINT       NOT NULL COMMENT '培训课程',
    start_date     DATE         NOT NULL COMMENT '开班日期',
    end_date       DATE         NOT NULL COMMENT '结班日期',
    quota          INT          NOT NULL DEFAULT 20 COMMENT '名额上限',
    enrolled_count INT          NOT NULL DEFAULT 0 COMMENT '已通过人数',
    version        INT          NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    status         TINYINT      NOT NULL DEFAULT 0 COMMENT '0草稿 1已发布 2已结束',
    create_time    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    deleted        TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    PRIMARY KEY (id),
    KEY idx_course (course_id),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='培训班表';

-- -------------------------------------------------------------
-- 6. 报名表（一个学员对一个班只能报一次）
-- -------------------------------------------------------------
CREATE TABLE enroll (
    id          BIGINT   NOT NULL AUTO_INCREMENT COMMENT '主键',
    class_id    BIGINT   NOT NULL COMMENT '培训班',
    user_id     BIGINT   NOT NULL COMMENT '学员',
    status      TINYINT  NOT NULL DEFAULT 0 COMMENT '0待审批 1已通过 2已驳回 3已取消',
    progress    INT      NOT NULL DEFAULT 0 COMMENT '学习进度 0-100',
    score       INT      DEFAULT NULL COMMENT '考试成绩',
    passed      TINYINT  DEFAULT NULL COMMENT '是否通过 0否 1是',
    ai_comment  TEXT     NULL COMMENT 'AI 学习评语',
    comment_time DATETIME NULL COMMENT '评语生成时间',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '报名时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_class_user (class_id, user_id),
    KEY idx_user (user_id),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='报名表';

-- -------------------------------------------------------------
-- 7. 题库表（options 用 JSON 数组存，省一张选项表）
-- -------------------------------------------------------------
CREATE TABLE question (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
    course_id   BIGINT       NOT NULL COMMENT '所属课程',
    type        VARCHAR(20)  NOT NULL DEFAULT 'SINGLE' COMMENT 'SINGLE单选 MULTI多选',
    stem        VARCHAR(500) NOT NULL COMMENT '题干',
    options     JSON         NOT NULL COMMENT '选项 [{"k":"A","v":"..."}]',
    answer      VARCHAR(20)  NOT NULL COMMENT '正确答案，多选用逗号分隔',
    score       INT          NOT NULL DEFAULT 10 COMMENT '分值',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_course (course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='题库表';

-- -------------------------------------------------------------
-- 8. 考试记录表
-- -------------------------------------------------------------
CREATE TABLE exam_record (
    id           BIGINT   NOT NULL AUTO_INCREMENT COMMENT '主键',
    class_id     BIGINT   NOT NULL COMMENT '培训班',
    user_id      BIGINT   NOT NULL COMMENT '学员',
    score        INT      NOT NULL DEFAULT 0 COMMENT '得分',
    passed       TINYINT  NOT NULL DEFAULT 0 COMMENT '是否通过',
    answer_json  TEXT     COMMENT '作答明细 JSON',
    start_time   DATETIME COMMENT '开始作答时间',
    submit_time  DATETIME COMMENT '提交时间',
    create_time  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    ai_comment   TEXT     COMMENT 'AI 考试评语',
    comment_time DATETIME COMMENT '评语生成时间',
    PRIMARY KEY (id),
    KEY idx_class_user (class_id, user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='考试记录表';

-- -------------------------------------------------------------
-- 9. 章节学习记录表（一个报名对同一章节只允许一条记录）
-- -------------------------------------------------------------
CREATE TABLE learn_record (
    id          BIGINT   NOT NULL AUTO_INCREMENT COMMENT '主键',
    enroll_id   BIGINT   NOT NULL COMMENT '报名记录',
    chapter_id  BIGINT   NOT NULL COMMENT '章节',
    user_id     BIGINT   NOT NULL COMMENT '学员（冗余，便于按人统计）',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '完成时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_enroll_chapter (enroll_id, chapter_id),
    KEY idx_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='章节学习记录表';

