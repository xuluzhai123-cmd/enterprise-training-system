    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '生成时间',
    PRIMARY KEY (id),
    KEY idx_course (course_id),
    KEY idx_chapter (chapter_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='RAG 知识切片';

-- -------------------------------------------------------------
-- 演示数据校准：补考学员的故事要讲得通
-- 每个考了两次的学员：第一次未通过、第二次通过
-- （否则成绩页的「第1次/第2次」标签会显示成"第一次过了、第二次反而没过"）
-- -------------------------------------------------------------
UPDATE exam_record e
JOIN (SELECT class_id, user_id, MIN(id) AS fid, MAX(id) AS lid
      FROM exam_record GROUP BY class_id, user_id HAVING COUNT(*) = 2) p
  ON e.id = p.fid
SET e.score = 35 + (e.id % 20), e.passed = 0;

UPDATE exam_record e
JOIN (SELECT class_id, user_id, MIN(id) AS fid, MAX(id) AS lid
      FROM exam_record GROUP BY class_id, user_id HAVING COUNT(*) = 2) p
  ON e.id = p.lid
SET e.score = 68 + (e.id % 25), e.passed = 1;

-- 报名记录上的最高分/是否通过，按考试记录重算
UPDATE enroll en
JOIN (SELECT class_id, user_id, MAX(score) AS mx FROM exam_record GROUP BY class_id, user_id) t
  ON en.class_id = t.class_id AND en.user_id = t.user_id
SET en.score = t.mx, en.passed = IF(t.mx >= 60, 1, 0);
